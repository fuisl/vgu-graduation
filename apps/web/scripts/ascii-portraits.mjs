#!/usr/bin/env node
/**
 * Regenerates the ASCII developer portraits on /about (#7) from public GitHub avatars.
 *
 *   node apps/web/scripts/ascii-portraits.mjs           # writes app/about/portraits.generated.ts
 *   node apps/web/scripts/ascii-portraits.mjs --print   # prints the portraits instead
 *
 * Run it by hand when an avatar changes; the output is committed so the build never touches the
 * network. Each avatar is reduced to a 48x29 grid (a cell is 0.6em wide and 1em tall, so the grid
 * is square on screen), contrast-stretched, faded to blank outside an oval and mapped onto the
 * landing sculpture's 10-glyph ramp, densest where the avatar is brightest (white on blue).
 */
import { writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

// sharp is not a dependency of @grad/web; borrow Next's copy (an optional dependency of next).
const require = createRequire(import.meta.url);
const sharp = createRequire(require.resolve("next/package.json"))("sharp");

export const COLS = 48;
export const ROWS = 29; // COLS x 0.6, rounded
/** Same ramp as the landing sculpture (landing.md, ASCII rendering), sparsest to densest. */
export const RAMP = " .:-=+*#%@";

/** `invert` (chosen by eye) draws dark features densest, for avatars on a light background. Order is display order. */
const DEVELOPERS = [
  { handle: "fuisl", invert: false },
  { handle: "nhientruong04", invert: true },
  { handle: "dducwsxuaan", invert: false },
  { handle: "AndrwPham", invert: true },
];

const here = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(here, "../app/about/portraits.generated.ts");

async function portrait({ handle, invert }) {
  const res = await fetch(`https://github.com/${handle}.png?size=240`);
  if (!res.ok) throw new Error(`${handle}: avatar request failed (${res.status})`);
  const input = Buffer.from(await res.arrayBuffer());
  const { data } = await sharp(input)
    .flatten({ background: "#ffffff" })
    .greyscale()
    .resize(COLS, ROWS, { fit: "fill", kernel: "lanczos3" })
    .raw()
    .toBuffer({ resolveWithObject: true });

  const values = Array.from(data, (v) => (invert ? 255 - v : v) / 255);
  // Stretch the 3rd to 97th percentile to the full ramp so dim photos still use every glyph.
  const sorted = [...values].sort((a, b) => a - b);
  const lo = sorted[Math.floor(sorted.length * 0.03)];
  const hi = sorted[Math.floor(sorted.length * 0.97)];
  const span = Math.max(hi - lo, 1e-3);

  const rows = [];
  for (let y = 0; y < ROWS; y += 1) {
    let row = "";
    for (let x = 0; x < COLS; x += 1) {
      const v = Math.min(1, Math.max(0, (values[y * COLS + x] - lo) / span));
      // Oval fade in screen space (the grid is square on screen): full inside 0.78, blank past 1.
      const dx = (x + 0.5) / COLS - 0.5;
      const dy = (y + 0.5) / ROWS - 0.5;
      const d = Math.hypot(dx, dy) / 0.5;
      const t = Math.min(1, Math.max(0, (1 - d) / (1 - 0.78)));
      const fade = t * t * (3 - 2 * t);
      row += RAMP[Math.min(RAMP.length - 1, Math.floor(v * fade * RAMP.length))];
    }
    rows.push(row.replace(/\s+$/, ""));
  }
  return rows.join("\n");
}

const portraits = [];
for (const dev of DEVELOPERS) portraits.push([dev.handle, await portrait(dev)]);

if (process.argv.includes("--print")) {
  for (const [handle, art] of portraits) console.log(`${handle}\n${art}\n`);
} else {
  const body = portraits.map(([handle, art]) => `  ${JSON.stringify(handle)}: [\n${art.split("\n").map((r) => `    ${JSON.stringify(r)},`).join("\n")}\n  ].join("\\n"),`).join("\n");
  await writeFile(
    OUT,
    `// Generated by apps/web/scripts/ascii-portraits.mjs from public GitHub avatars. Do not edit by hand.\n` +
      `// ${COLS}x${ROWS} cells, ramp ${JSON.stringify(RAMP)}.\n\n` +
      `export const PORTRAIT_COLS = ${COLS};\nexport const PORTRAIT_ROWS = ${ROWS};\n\n` +
      `export const PORTRAITS: Readonly<Record<string, string>> = {\n${body}\n};\n`,
  );
  console.log(`wrote ${path.relative(process.cwd(), OUT)}`);
}
